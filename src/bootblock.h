/* UCSD p-System / Apple Pascal boot blocks.
 *
 * Unlike ProDOS, Pascal has no single bootstrap that serves every device.
 * The 5.25" bootstrap talks to the Disk II controller directly and spans
 * two blocks; the 3.5"/hard-disk bootstrap makes ProDOS-style block-driver
 * calls and fits in block 0 alone. Both do the same job: scan the volume
 * directory for SYSTEM.APPLE (the p-System interpreter) and load it. That
 * makes them version-neutral in practice, since the version lives in the
 * system files on the volume, not in the bootstrap.
 */

